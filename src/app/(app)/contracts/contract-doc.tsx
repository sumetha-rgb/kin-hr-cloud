type Company = { name: string; address: string | null; taxId: string | null };

/** ตัวเลขเป็นตัวอักษรไทย เช่น 119 → หนึ่งร้อยสิบเก้า */
const thaiNumber = (n: number) => bahtText(Math.floor(n)).replace("บาทถ้วน", "");

/** เลขบัตรประชาชนแบบมีขีด */
const fmtId = (v: string | null | undefined) => (v && v.length === 13 ? `${v[0]}-${v.slice(1, 5)}-${v.slice(5, 10)}-${v.slice(10, 12)}-${v[12]}` : (v ?? ""));
const lines = (s: string | null | undefined) => (s ?? "").split("\n").map((x) => x.trim()).filter(Boolean);

/** ช่องกรอกข้อมูล (ขีดเส้นใต้) */
function F({ children, w = "min-w-24" }: { children?: React.ReactNode; w?: string }) {
  return <span className={cn("inline-block border-b border-dotted border-stone-500 px-1 text-center font-semibold", w)}>{children || " "}</span>;
}

/** หัวข้อ "ข้อ n." */
function Clause({ n, title, children }: { n: number; title: string; children: React.ReactNode }) {
  return (
    <section className="mt-3 break-inside-avoid-page">
      <p className="font-bold">
        ข้อ {n}. <span className="ml-2">{title}</span>
      </p>
      <div className="space-y-0.5 pl-[2.2em]">{children}</div>
    </section>
  );
}

/** รายการย่อย (1) (2) … และ (2.1) ย่อหน้าลึกขึ้น */
function Items({ text }: { text: string | null | undefined }) {
  return (
    <>
      {lines(text).map((t, i) => {
        const m = t.match(/^(\(\d+(?:\.\d+)?\))\s*(.*)$/);
        const sub = !!m && m[1].includes(".");
        return m ? (
          <p key={i} className={cn("flex gap-2", sub && "pl-[2.4em]")}>
            <span className="shrink-0">{m[1]}</span>
            <span>{m[2]}</span>
          </p>
        ) : (
          <p key={i}>{t}</p>
        );
      })}
    </>
  );
}

/** ตารางค่าจ้าง (ข้อ 12) */
function Pay({ rows, unit, conditions }: { rows: Array<{ label: string; amount: number }>; unit: string; conditions: string | null }) {
  const total = rows.reduce((a, r) => a + Number(r.amount || 0), 0);
  const conds = lines(conditions);
  return (
    <>
      <table className="my-1 w-full [&_td]:py-0.5 [&_td]:align-top">
        <tbody>
          {rows.map((r, i) => (
            <tr key={i}>
              <td className="w-8">({i + 1})</td>
              <td>{r.label} :</td>
              <td className="w-28 text-right font-semibold tabular-nums">{Number(r.amount) ? fmtMoney(r.amount) : "-"}</td>
              <td className="w-10 pl-2">บาท</td>
              <td className="text-stone-700">({bahtText(Number(r.amount) || 0)}) {unit}</td>
            </tr>
          ))}
          {unit === "ต่อเดือน" && rows.length > 1 && (
            <tr className="font-semibold">
              <td />
              <td>รวมค่าจ้างเดือนละ :</td>
              <td className="text-right tabular-nums">{fmtMoney(total)}</td>
              <td className="pl-2">บาท</td>
              <td>({bahtText(total)})</td>
            </tr>
          )}
        </tbody>
      </table>
      {conds.length > 0 && (
        <>
          <p>เงื่อนไขข้อตกลงอื่น ๆ (ถ้ามี) :</p>
          {conds.map((c, i) => (
            <p key={i} className="pl-[1.2em]">
              {conds.length > 1 ? `${i + 1}. ` : ""}
              {c}
            </p>
          ))}
        </>
      )}
    </>
  );
}

